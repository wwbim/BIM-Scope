  updateDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      if (el.id === 'project-title-text' && window.app && window.app.currentModelInfo && !window.app.currentModelInfo.isDemo) {
        return;
      }
      const key = el.getAttribute('data-i18n');
      if (el.querySelector && el.querySelector('svg')) {
        const textSpan = el.querySelector('span');
        if (textSpan) {
          textSpan.textContent = this.t(key);
          return;
        }
      }
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });
    
    const langBtn = document.getElementById('btn-lang-toggle');
    if (langBtn) {
      langBtn.innerHTML = this.currentLang === 'en' ? '🌐 中文' : '🌐 English';
    }

    // Refresh dynamic category legend chip labels if present
    if (window.app && window.app.categoryStates) {
      window.app.categoryStates.forEach((state, catName) => {
        const localizedName = this.getCategoryName(catName);
        state.localizedName = localizedName;
        if (state.chipEl) {
          const nameSpan = state.chipEl.querySelector('.legend-chip-name');
          if (nameSpan) nameSpan.textContent = localizedName;
          state.chipEl.title = `${localizedName} (${state.meshes.length}) - Click: Toggle | Alt-Click: Isolate`;
        }
      });
    }

    if (window.app) {
      if (typeof window.app.updateModelSubtitle === 'function') {
        window.app.updateModelSubtitle();
      }
      if (!window.app.selectedMesh && (!window.app.selectedMeshes || window.app.selectedMeshes.length === 0)) {
        if (typeof window.app.renderModelInfoInspector === 'function') {
          window.app.renderModelInfoInspector();
        }
      }
    }
  }
